/* tests/data/objects.c — exercises src/data/objects.c: the castle
 * metatile table against the disassembly, row by row. The bytes are the
 * CastleMetatiles .db rows from smb.asm (eleven rows of five), which
 * also match the cartridge's PRG image at $97CF. */
#include <assert.h>
#include <stdio.h>

#include "../../src/data/objects.h"

int main(void) {
  /* smb.asm: CastleMetatiles */
  static const uint8_t ROWS[11][5] = {
      {0x00, 0x45, 0x45, 0x45, 0x00}, {0x00, 0x48, 0x47, 0x46, 0x00},
      {0x45, 0x49, 0x49, 0x49, 0x45}, {0x47, 0x47, 0x4a, 0x47, 0x47},
      {0x47, 0x47, 0x4b, 0x47, 0x47}, {0x49, 0x49, 0x49, 0x49, 0x49},
      {0x47, 0x4a, 0x47, 0x4a, 0x47}, {0x47, 0x4b, 0x47, 0x4b, 0x47},
      {0x47, 0x47, 0x47, 0x47, 0x47}, {0x4a, 0x47, 0x4a, 0x47, 0x4a},
      {0x4b, 0x47, 0x4b, 0x47, 0x4b},
  };
  for (int r = 0; r < 11; r++) {
    for (int c = 0; c < 5; c++) {
      assert(SMBC_CASTLE_METATILES[r * 5 + c] == ROWS[r][c]);
    }
  }

  printf("tests/data/objects: ok\n");
  return 0;
}
